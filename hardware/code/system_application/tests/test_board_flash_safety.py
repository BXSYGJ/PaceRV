"""Guard the JTAG flashing flow against the FTDI drop bug (2026-10-29).

Root cause of "the downloader drops the moment you touch the board": the
flash script killed ``cdt_cfg.exe`` with ``Popen.terminate()`` right after
``PROGRAM FLOW DONE`` appeared, but that banner is printed *before* the TCL
interpreter reaches ``cfg_disconnect``/``exit``.  A terminated D2XX process
never releases the handle, so the FT2232H stops answering on the USB bus and
disappears from PnP (``CM_PROB_PHANTOM``) until the cable is re-plugged.

These tests pin the three rules that make the flow safe:

  R1  every generated / committed TCL script ends with ``exit`` so
      ``cdt_cfg`` finishes by itself;
  R2  no script in ``scripts/`` terminates or kills a JTAG process;
  R3  an already-open jtagserver port is reused instead of restarted.

They are pure static checks: no hardware, no PDS, no serial port needed.
"""

from __future__ import annotations

import re
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
SCRIPTS = ROOT / 'scripts'


def _jtag_tcls():
    return sorted(SCRIPTS.glob('jtag_*.tcl'))


def test_jtag_tcls_exist():
    assert _jtag_tcls(), 'no jtag_*.tcl scripts found'


@pytest.mark.parametrize('path', _jtag_tcls(), ids=lambda p: p.name)
def test_tcl_finishes_with_exit(path):
    """R1: cdt_cfg must be able to exit on its own."""
    lines = [ln.strip() for ln in path.read_text(encoding='utf-8').splitlines()]
    tail = [ln for ln in lines if ln and not ln.startswith('#')]
    assert tail, f'{path.name} is empty'
    assert tail[-1] == 'exit', (
        f'{path.name} does not end with "exit"; a TCL file without exit '
        f'makes cdt_cfg hang and the only way out is killing it, which drops '
        f'the FTDI device'
    )


def test_status_body_ends_with_exit():
    """R1: the TCL generated by board_check.py must also exit."""
    import board_check

    for sbit in (None, 'build/instrec-latest.sbit'):
        body = board_check.status_body(sbit)
        tail = [ln.strip() for ln in body.splitlines() if ln.strip()]
        assert tail[-1] == 'exit'
        assert 'cfg_disconnect' in body


def test_board_check_never_kills_jtag():
    """R2: no terminate/kill path may exist for cdt_cfg / cdt_js."""
    src = (SCRIPTS / 'board_check.py').read_text(encoding='utf-8')
    code = '\n'.join(ln for ln in src.splitlines() if not ln.lstrip().startswith('#'))
    for pattern in (r'\.terminate\s*\(', r'\.kill\s*\(', r'Stop-Process',
                    r'taskkill', r'os\.kill'):
        assert not re.search(pattern, code), f'forbidden process kill: {pattern}'
    assert '_ = proc.wait(timeout=timeout)' in src or 'proc.wait(timeout=' in src


def test_board_check_reuses_running_server():
    """R3: an existing jtagserver must be reused, never restarted or duplicated."""
    src = (SCRIPTS / 'board_check.py').read_text(encoding='utf-8')
    assert 'state, pid = ensure_server()' in src
    assert 'reusing the running jtagserver (PID' in src
    # a server that exists but is not listening yet must be waited for,
    # never replaced by a second instance
    assert 'NOT starting a second instance' in src
    # the old buggy shape returned failure whenever the port was already open
    assert 'if js is None:' not in src

def test_single_jtagserver_instance():
    """Starting a second jtagserver is a defect: reuse, never spawn alongside."""
    src = (SCRIPTS / 'board_check.py').read_text(encoding='utf-8')
    assert 'def ensure_server(' in src
    assert 'def jtag_procs(' in src
    # the spawn path must be guarded by an instance check
    assert "pids = jtag_procs()" in src
    assert "pid = start_server()" in src
    assert "if pid is None:" in src
    # and multiple instances must be reported, not silently accepted
    assert 'MULTIPLE UIs' in src
    assert 'instances grew' in src


def test_no_second_cdt_cfg_left_behind():
    """A hung cdt_cfg is reported and left alone (killing drops the FTDI)."""
    src = (SCRIPTS / 'board_check.py').read_text(encoding='utf-8')
    assert 'LEFT RUNNING on purpose' in src
    assert 'cdt_cfg did not exit within the timeout' in src
