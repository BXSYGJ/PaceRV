#!/usr/bin/env python3
"""Generate the class label character ROM for the InstRec UI (M3).

Packs the eight English class names from
scripts/outputs/layer_contract.json (classes.names) into fixed-length
character records so that RTL can address one character as

    label_rom[(class_index << 5) + char_column]

Each record is 32 ASCII characters, space padded; 8 * 32 = 256 bytes.
(24 was the planned width but the longest name, "distorted electric
guitar", is 25 characters; 32 keeps the stride a power of two so the RTL
address needs no multiply. text_disp.v draws only the real name length
from its own length table and places the percentage right after it.)
Output: src/ui/class_labels.hex, one hex byte per line (font_rom.v /
text_disp.v read it with $readmemh). The leading "//" lines of the hex
file document the layout and are skipped by $readmemh.

Usage: python scripts/gen_label_rom.py
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONTRACT = ROOT / 'scripts/outputs/layer_contract.json'
OUT = ROOT / 'src/ui/class_labels.hex'

N_CLASSES = 8
NAME_LEN = 32   # power-of-two stride: address = (class << 5) + column


def load_names() -> list[str]:
    with CONTRACT.open(encoding='utf-8') as fh:
        contract = json.load(fh)
    names = contract['classes']['names']
    if len(names) != N_CLASSES:
        raise SystemExit(f'expected {N_CLASSES} class names, got {len(names)}')
    for name in names:
        if len(name) > NAME_LEN:
            raise SystemExit(
                f'class name {name!r} is {len(name)} chars, '
                f'record is {NAME_LEN}: widen NAME_LEN and text_disp too'
            )
        if not name.isascii() or not name.isprintable():
            raise SystemExit(f'class name {name!r} is not printable ASCII')
    return names


def main() -> None:
    names = load_names()
    header = [
        '// InstRec-FPGA class label ROM (M3). Generated by'
        ' scripts/gen_label_rom.py, do not edit.',
        '// Layout: 8 classes x 32 ASCII chars, space padded, 256 bytes, one'
        ' hex byte per line.',
        '// Address of one character: (class_index << 5) + char_column; the'
        ' unused tail columns of',
        '// each record are 0x20 (space) so their glyph is blank; text_disp.v'
        ' draws only the real name',
        '// length from its own table and then the percentage field.',
        '// Source: scripts/outputs/layer_contract.json classes.names'
        ' (asserted against InstRec R-06).',
    ]
    for idx, name in enumerate(names):
        header.append(f'// class {idx}: len={len(name):2d} {name}')
    body = []
    for name in names:
        record = name.ljust(NAME_LEN, ' ')
        body.extend(f'{ord(ch):02x}' for ch in record)
    OUT.write_text('\n'.join(header + body) + '\n', encoding='ascii', newline='\n')
    print(f'wrote {OUT} ({len(body)} bytes, {N_CLASSES} x {NAME_LEN} chars)')
    print('text_disp.v name length table (class -> chars):')
    for idx, name in enumerate(names):
        print(f'  [{idx}] {len(name):2d} {name}')


if __name__ == '__main__':
    main()