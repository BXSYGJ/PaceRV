"""Generate the exact 147-phase 48k -> 44.1k FIR (Q1.15)."""
from pathlib import Path
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
TAPS = 96
PHASES = 147

def coefficients():
    k = np.arange(TAPS)
    rows = []
    for phase in range(PHASES):
        x = k - 47 - phase / PHASES
        window = np.i0(7.5 * np.sqrt(np.maximum(0, 1 - (x / 48)**2))) / np.i0(7.5)
        h = (41000 / 48000) * np.sinc((41000 / 48000) * x) * window
        q = np.rint(h / h.sum() * 32768).astype(np.int64)
        q[47] += 32768 - q.sum()
        rows.append(q)
    return np.array(rows)

def main():
    q = coefficients()
    lines = ['// Module: pcm1808_coeff_rom', '// Generated by scripts/gen_pcm1808_filter.py. Do not hand edit.',
             '// Exact phase symmetry with DC-rounding corrections.',
             'module pcm1808_coeff_rom (',
             '    input wire clk, input wire [7:0] phase, input wire [6:0] tap,',
             '    output wire signed [15:0] coeff', ');',
             "    wire mirrored = phase > 8'd73;",
             "    wire [7:0] base_phase = mirrored ? 8'd147 - phase : phase;",
             "    wire [6:0] base_tap = mirrored ? 7'd95 - tap : tap;",
             "    wire [12:0] addr = base_phase * 13'd96 + base_tap;",
             '    reg signed [15:0] base_coeff;',
             '    reg signed [4:0] correction, correction_pipe;',
             '    assign coeff = base_coeff + {{11{correction_pipe[4]}}, correction_pipe};',
             '    always @* begin', "        correction = 5'sd0;", '        case (phase)']
    for phase in range(74,147):
        correction = int(q[phase,47] - q[147-phase,48])
        restored = q[147-phase,::-1].copy()
        restored[47] += correction
        restored[48] -= correction
        assert np.array_equal(restored, q[phase])
        lines.append("            8'd%d: correction = 5'h%02x;" % (phase, correction & 31))
    lines += ["            default: correction = 5'sd0;", '        endcase', '    end',
              '    always @(posedge clk) begin',
              "        if (mirrored && tap == 7'd47) correction_pipe <= correction;",
              "        else if (mirrored && tap == 7'd48) correction_pipe <= -correction;",
              "        else correction_pipe <= 5'sd0;", '        case (addr)']
    for address, value in enumerate(q[:74].flat):
        lines.append("            13'd%d: base_coeff <= 16'h%04x;" % (address, int(value) & 65535))
    lines += ["            default: base_coeff <= 16'd0;", '        endcase', '    end', 'endmodule', '']
    (ROOT / 'src/audio/pcm1808_coeff_rom.v').write_text('\n'.join(lines), encoding='ascii')

if __name__ == '__main__':
    main()
