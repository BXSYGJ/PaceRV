// -----------------------------------------------------------------------------
// diag_uart_report - fixed-format ASCII diagnostic frame generator
//                    (contract C-DIAG-UART@1, plan P1 section 2.2.3)
// -----------------------------------------------------------------------------
// One frame is one ASCII line, always 91 bytes, terminated by a newline:
//
//   DIAG <TAG8> A=<8 hex> B=<8 hex> C=<8 hex> D=<8 hex> E=<8 hex> F=<8 hex> G=<2 hex> H=<2 hex>\n
//
// Byte accounting (asserted by tests/test_diag_uart_report.py):
//   prefix DIAG plus space                     5
//   tag field, always 8 bytes (space padded)   8
//   separator space                            1
//   six 32-bit fields  X=xxxxxxxx plus space   6 * 11 = 66
//   two  8-bit  fields  X=xx plus space        2 *  5 = 10
//   newline                                    1
//   ----------------------------------------------------
//   total                                     91
//
// The plan text quotes 86 bytes for the same template.  The byte-accurate
// count of the template above is 91: the tag field is fixed at 8 bytes and
// each of the eight value fields carries its own trailing space.  This
// module and scripts/diag_frames.py implement 91, the test suite pins 91,
// and the discrepancy with the plan text is reported to the team leader.
//
// Frame duration, BAUD_DIV clock cycles per bit, 10 bit times per byte:
//   FRAME_CYCLES = 91 * 10 * BAUD_DIV
//   BAUD_DIV 1085 at 125.0 MHz  -> 987350 cycles -> 7.90 ms
//   BAUD_DIV 1289 at 148.5 MHz  -> 1172990 cycles -> 7.90 ms
// With a 25 ms frame period that is 7.90 / 25 = 31.6 percent duty, so
// consecutive frames never overlap and uart_tx is idle between them.
//
// Behaviour (plan section 2.2.3 rules D1..D5):
//   D1  fire is a one-cycle request; a fire while busy is DROPPED.
//   D2  tx_byte_valid is a level handshake: the byte is presented and held
//       until tx_byte_ready is seen high, then valid drops for exactly one
//       cycle before the next byte is presented.  The one-cycle gap is
//       required by uart_tx.v, whose byte_wready is a register that stays
//       high for one extra cycle after an accept; it is the same hazard that
//       broke uart_debug.v character sequencing.
//   D3  uppercase hex digits, 8 nibbles (MSB first) for A..F and 2 nibbles
//       for G/H, all zero padded.
//   D4  busy is high from the accepted fire until the last newline byte has
//       been accepted by uart_tx.
//   D5  reset drives busy and tx_byte_valid low; no frame is emitted
//       spontaneously after power-up.
//
// Text is generated by an explicit ASCII case table only.  No string
// literal appears anywhere in this file: PDS string-literal byte order is
// not reproducible (the uart_debug.v ITCO incident in HANDOFF_SNAPSHOT).
//
// Storage: the frame is NOT buffered.  Each byte position is rendered
// combinationally from the latched sample, which is logically equivalent to
// writing the whole 91-byte frame into a RAM first, but costs no block RAM
// and no 768 flip-flops (96 bytes x 8).  The plan mentions a 96-byte frame
// buffer only as an upper bound for the 91-byte frame; the buffer itself is
// an implementation detail, not part of the observable contract.
//
// All logic is in the clk domain; reset is asynchronous, active low.
// -----------------------------------------------------------------------------
module diag_uart_report #(
    parameter integer BAUD_DIV = 1085   // 1085 -> 125 MHz, 1289 -> 148.5 MHz
) (
    input  wire        clk,
    input  wire        rst_n,
    input  wire        fire,          // one-cycle: emit one frame (ignored while busy)
    input  wire [1:0]  frame_tag,     // 0 DDR3DIAG, 1 UIDEMO, 2 DDR3SW, 3 DDR3RS
    input  wire [31:0] f_a, f_b, f_c, f_d, f_e, f_f,
    input  wire [7:0]  f_g, f_h,
    output wire        busy,
    output reg  [7:0]  tx_byte_data,
    output reg         tx_byte_valid,
    input  wire        tx_byte_ready
);

    // ------------------------------------------------------------------
    // Frame geometry.  All byte positions are 0 based and inclusive.
    // ------------------------------------------------------------------
    localparam integer FRAME_LEN    = 91;
    localparam integer FRAME_CYCLES = FRAME_LEN * 10 * BAUD_DIV;

    localparam [7:0] POS_PREFIX_END = 8'd5;    // DIAG plus one space
    localparam [7:0] POS_TAG_END    = 8'd13;   // 5 + 8 tag bytes
    localparam [7:0] POS_SEPARATOR  = 8'd13;   // one space after the tag field
    localparam [7:0] POS_F32_BASE   = 8'd14;   // first 32-bit field starts here
    localparam [7:0] POS_F32_END    = 8'd80;   // 14 + 6 * 11
    localparam [7:0] POS_F8_BASE    = 8'd80;   // first 8-bit field starts here
    localparam [7:0] POS_F8_END     = 8'd90;   // 80 + 2 * 5
    localparam [7:0] POS_NEWLINE    = 8'd90;   // last byte of the frame

    localparam [7:0] CH_SPACE = 8'h20;
    localparam [7:0] CH_EQUAL = 8'h3D;
    localparam [7:0] CH_NL    = 8'h0A;

    // ------------------------------------------------------------------
    // Frame snapshot.  Every byte of one frame is rendered from the sample
    // taken on the accepted fire, so a frame is internally consistent even
    // when the upstream counters keep moving (frame takes ~7.9 ms).
    // ------------------------------------------------------------------
    reg [1:0]  tag_q;
    reg [31:0] a_q, b_q, c_q, d_q, e_q, f_q;
    reg [7:0]  g_q, h_q;

    // ------------------------------------------------------------------
    // Transmitter state.
    // ------------------------------------------------------------------
    reg        busy_q;
    reg [7:0]  pos;            // byte position being presented (0..90)
    reg [2:0]  tag_idx;        // 0..7 index inside the tag field
    reg [7:0]  rel_pos;        // offset inside the current segment
    reg [2:0]  fld_idx;        // 0..5 -> A..F, 6 -> G, 7 -> H
    reg [7:0]  seg_off;        // offset inside one 11-byte or 5-byte field
    reg [31:0] field_word;     // selected 32-bit payload
    reg [7:0]  byte_val;       // selected 8-bit payload
    reg [7:0]  field_letter;   // field name character (A..H)
    reg [7:0]  tag_char;       // tag field character
    reg [7:0]  cur_char;       // ASCII byte at position pos

    assign busy = busy_q;

    // Uppercase hex digit of a 4-bit nibble (0-9A-F).  Same arithmetic as
    // hex_ascii() in uart_debug.v, kept explicit so no lookup ROM is needed.
    function [7:0] hex_nib;
        input [3:0] nib;
        begin
            hex_nib = (nib >= 4'hA) ? (8'h41 + {4'd0, nib - 4'hA})
                                    : (8'h30 + {4'd0, nib});
        end
    endfunction

    // ------------------------------------------------------------------
    // Combinational byte renderer: ASCII byte for the current byte position.
    // The position map is fixed and mirrors the frame template above.
    // ------------------------------------------------------------------
    always @* begin
        tag_char     = CH_SPACE;
        tag_idx      = 3'd0;
        rel_pos      = 8'd0;
        fld_idx      = 3'd0;
        seg_off      = 8'd0;
        field_word   = 32'd0;
        byte_val     = 8'd0;
        field_letter = 8'h41;
        cur_char     = CH_SPACE;

        if (pos < POS_PREFIX_END) begin
            // pos 0..4: fixed prefix, always the same five bytes.
            case (pos)
                8'd0: cur_char = 8'h44;   // 'D'
                8'd1: cur_char = 8'h49;   // 'I'
                8'd2: cur_char = 8'h41;   // 'A'
                8'd3: cur_char = 8'h47;   // 'G'
                8'd4: cur_char = 8'h20;   // ' '
                default: cur_char = CH_SPACE;
            endcase
        end else if (pos < POS_TAG_END) begin
            // pos 5..12: tag field, always 8 bytes.  The selected name is
            // right padded with spaces so the frame length never changes.
            tag_idx = pos - POS_PREFIX_END;
            case ({tag_q, tag_idx})
                // frame_tag 0: DDR3DIAG (8 characters, no padding)
                5'd0:  tag_char = 8'h44;   // 'D'
                5'd1:  tag_char = 8'h44;   // 'D'
                5'd2:  tag_char = 8'h52;   // 'R'
                5'd3:  tag_char = 8'h33;   // '3'
                5'd4:  tag_char = 8'h44;   // 'D'
                5'd5:  tag_char = 8'h49;   // 'I'
                5'd6:  tag_char = 8'h41;   // 'A'
                5'd7:  tag_char = 8'h47;   // 'G'
                // frame_tag 1: UIDEMO (6 characters + 2 spaces)
                5'd8:  tag_char = 8'h55;   // 'U'
                5'd9:  tag_char = 8'h49;   // 'I'
                5'd10: tag_char = 8'h44;   // 'D'
                5'd11: tag_char = 8'h45;   // 'E'
                5'd12: tag_char = 8'h4D;   // 'M'
                5'd13: tag_char = 8'h4F;   // 'O'
                5'd14: tag_char = 8'h20;   // ' '
                5'd15: tag_char = 8'h20;   // ' '
                // frame_tag 2: DDR3SW (6 characters + 2 spaces)
                5'd16: tag_char = 8'h44;   // 'D'
                5'd17: tag_char = 8'h44;   // 'D'
                5'd18: tag_char = 8'h52;   // 'R'
                5'd19: tag_char = 8'h33;   // '3'
                5'd20: tag_char = 8'h53;   // 'S'
                5'd21: tag_char = 8'h57;   // 'W'
                5'd22: tag_char = 8'h20;   // ' '
                5'd23: tag_char = 8'h20;   // ' '
                // frame_tag 3: DDR3RS (6 characters + 2 spaces)
                5'd24: tag_char = 8'h44;   // 'D'
                5'd25: tag_char = 8'h44;   // 'D'
                5'd26: tag_char = 8'h52;   // 'R'
                5'd27: tag_char = 8'h33;   // '3'
                5'd28: tag_char = 8'h52;   // 'R'
                5'd29: tag_char = 8'h53;   // 'S'
                5'd30: tag_char = 8'h20;   // ' '
                5'd31: tag_char = 8'h20;   // ' '
                default: tag_char = CH_SPACE;
            endcase
            cur_char = tag_char;
        end else if (pos == POS_SEPARATOR) begin
            // pos 13: single space between the tag field and field A.
            cur_char = CH_SPACE;
        end else if (pos < POS_F32_END) begin
            // pos 14..79: six fields of 11 bytes: X=xxxxxxxx plus a space.
            rel_pos = pos - POS_F32_BASE;
            if (rel_pos < 8'd11) begin
                fld_idx = 3'd0;
                seg_off = rel_pos;
            end else if (rel_pos < 8'd22) begin
                fld_idx = 3'd1;
                seg_off = rel_pos - 8'd11;
            end else if (rel_pos < 8'd33) begin
                fld_idx = 3'd2;
                seg_off = rel_pos - 8'd22;
            end else if (rel_pos < 8'd44) begin
                fld_idx = 3'd3;
                seg_off = rel_pos - 8'd33;
            end else if (rel_pos < 8'd55) begin
                fld_idx = 3'd4;
                seg_off = rel_pos - 8'd44;
            end else begin
                fld_idx = 3'd5;
                seg_off = rel_pos - 8'd55;
            end

            case (fld_idx)
                3'd0: field_word = a_q;
                3'd1: field_word = b_q;
                3'd2: field_word = c_q;
                3'd3: field_word = d_q;
                3'd4: field_word = e_q;
                default: field_word = f_q;
            endcase
            field_letter = 8'h41 + {5'd0, fld_idx};   // 'A' .. 'F'

            case (seg_off)
                8'd0: cur_char = field_letter;
                8'd1: cur_char = CH_EQUAL;
                8'd2: cur_char = hex_nib(field_word[31:28]);
                8'd3: cur_char = hex_nib(field_word[27:24]);
                8'd4: cur_char = hex_nib(field_word[23:20]);
                8'd5: cur_char = hex_nib(field_word[19:16]);
                8'd6: cur_char = hex_nib(field_word[15:12]);
                8'd7: cur_char = hex_nib(field_word[11:8]);
                8'd8: cur_char = hex_nib(field_word[7:4]);
                8'd9: cur_char = hex_nib(field_word[3:0]);
                default: cur_char = CH_SPACE;         // seg_off 10
            endcase
        end else if (pos < POS_F8_END) begin
            // pos 80..89: two fields of 5 bytes: X=xx plus a space.
            rel_pos = pos - POS_F8_BASE;
            if (rel_pos < 8'd5) begin
                fld_idx = 3'd6;
                byte_val = g_q;
                seg_off = rel_pos;
            end else begin
                fld_idx = 3'd7;
                byte_val = h_q;
                seg_off = rel_pos - 8'd5;
            end
            field_letter = 8'h41 + {5'd0, fld_idx};   // 'G' and 'H'

            case (seg_off)
                8'd0: cur_char = field_letter;
                8'd1: cur_char = CH_EQUAL;
                8'd2: cur_char = hex_nib(byte_val[7:4]);
                8'd3: cur_char = hex_nib(byte_val[3:0]);
                default: cur_char = CH_SPACE;         // seg_off 4
            endcase
        end else if (pos == POS_NEWLINE) begin
            // pos 90: line terminator.
            cur_char = CH_NL;
        end
    end

    // ------------------------------------------------------------------
    // Frame engine: fire latch plus the level handshake to uart_tx.
    // ------------------------------------------------------------------
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            // D5: no spontaneous frame after reset.
            tag_q         <= 2'd0;
            a_q           <= 32'd0;
            b_q           <= 32'd0;
            c_q           <= 32'd0;
            d_q           <= 32'd0;
            e_q           <= 32'd0;
            f_q           <= 32'd0;
            g_q           <= 8'd0;
            h_q           <= 8'd0;
            busy_q        <= 1'b0;
            pos           <= 8'd0;
            tx_byte_data  <= 8'd0;
            tx_byte_valid <= 1'b0;
        end else if (!busy_q) begin
            // Idle.  A fire here starts exactly one frame; a fire while
            // busy never reaches this branch, so it is dropped (D1).
            if (fire) begin
                busy_q        <= 1'b1;
                pos           <= 8'd0;
                tag_q         <= frame_tag;
                a_q           <= f_a;
                b_q           <= f_b;
                c_q           <= f_c;
                d_q           <= f_d;
                e_q           <= f_e;
                f_q           <= f_f;
                g_q           <= f_g;
                h_q           <= f_h;
                tx_byte_data  <= cur_char;   // pos 0 is always 'D'
                tx_byte_valid <= 1'b1;
            end
        end else begin
            // Busy: one byte in flight at a time (D2 level handshake).
            if (tx_byte_valid) begin
                if (tx_byte_ready) begin
                    tx_byte_valid <= 1'b0;
                    if (pos == POS_NEWLINE) begin
                        // D4: the last newline byte was taken by uart_tx.
                        busy_q <= 1'b0;
                        pos    <= 8'd0;
                    end else begin
                        pos <= pos + 8'd1;
                    end
                end
            end else begin
                // One idle valid cycle after every accept: this absorbs the
                // extra high cycle of uart_tx byte_wready and presents the
                // next byte at position pos.
                tx_byte_data  <= cur_char;
                tx_byte_valid <= 1'b1;
            end
        end
    end

endmodule