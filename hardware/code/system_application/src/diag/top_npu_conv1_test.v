// ---------------------------------------------------------------------------
// top_npu_conv1_test.v -- conv1-only NPU verification top level (T22)
//
// PURPOSE
//   The NPU compute engines (conv_engine / pool_engine / gap_unit /
//   fc_engine / softmax_top) have only ever been proven at compile level.
//   The full-model weights live in DDR3 and that path is still unproven, so
//   this bitstream removes the DDR3 dependency for ONE layer: the entire
//   conv1 tensor is held in on-chip ROMs, the golden Mel feature map is
//   replayed from a ROM, conv_engine runs exactly one layer, and a sampled
//   copy of the egress stream is streamed over UART for a byte-exact
//   comparison against reports/golden_ref/sine_440_full/conv1.npy
//   (scripts/compare_conv1.py is the reader half).
//
//   This answers ONE question: is the conv1 MAC / requant / scan /
//   line-buffer datapath bit-exact against the golden?  It is an independent
//   verification line and deliberately does not touch DDR3 (no ddr3_wrapper,
//   no ddr3_ctrl_axi, no ddr3_100h.fdc here).
//
// CLOCK
//   27 MHz board clock (D18) straight into the whole design.  No PLL and no
//   DDR3 PHY, hence no core_clk / ref_clk_p domain and no generated clock.
//
// CYCLE / TIME BUDGET (conv1, full 64 x 258 x 48 geometry)
//   MAC count           : 48 * 64 * 258 * 9 = 7,133,184 signed MACs
//   16-lane array       : >= 445,824 MAC beats (16 lanes wide)
//   measured beat plan  : 49,536 pixels * 3 groups * 17 beats/px/grp
//                         = 842,112 scan beats (the 16-beat requant TDM
//                         drain, not the 12-beat tap scan, sets the pace)
//   ingress             : 64 rows * 258 columns = 16,512 beats, interleaved
//                         behind the row scan (row r+2 is written only after
//                         row r has been scanned, so the 3-bank line buffer
//                         is never clobbered under the active window)
//   boot (contract+taps) : 2 jobs * (49 + 37) = 172 beats
//   total               : ~858,600 beats @ 27 MHz = ~31.8 ms
//   UART                : (3 status + 128 data) * 91 bytes * 10 bits
//                         @ 115200 = ~1.03 s  ->  whole run < 1.1 s
//   27 MHz is therefore ample; a PLL would only add a second clock domain.
//
// WEIGHT / CONTRACT STORAGE (hex_conv1/, generated by
// scripts/compare_conv1.py --emit-hex from scripts/outputs/weights_image.bin
// at the layer contract offsets: 432 B weight + 192 B bias + 192 B M +
// 48 B shift, segment base 512, bias_off 432, m_off 624, shift_off 816)
//   conv1_w32.hex   : 108 x 32-bit words = the 27 tap words (16 signed lanes
//                     each, lane 0 in bits [7:0]) split into 4 words per tap.
//                     Group-major image order == the tap stream order
//                     conv_engine consumes, so no re-interleave is needed.
//   conv1_ctr.hex   : 144 x 32-bit words = 48 bias + 48 M + 48 shift.
//   conv1_feat.hex  : 16,512 x u8 = the golden (64, 258) uint8 feature map
//                     (zp_in = 49), replayed as the conv1 ingress stream in
//                     row-major / channel-major-within-row order.
//
// CONTRACT / TAP STREAM PROTOCOL (must match conv_engine.v exactly)
//   conv_engine's group-contract loader counts 48 strobes (16 bias, 16 M,
//   16 shift) and clears its counter on grp_start.  grp_start therefore gets
//   its OWN beat with no valid strobe: if grp_start coincided with the first
//   bias beat, cload_cnt would stay 0 for two beats and bias[1] would
//   overwrite bias[0].  This module gives grp_start one clean beat (c_step 0)
//   that also prefetches ROM word 0, then 48 valid beats (c_step 1..48)
//   carrying words 0..47.
//   There is a SECOND ordering constraint, easy to get wrong: conv_engine
//   clears grp_arm on any_start, so the first contract load MUST come after
//   the start0 pulse, otherwise the loaded active bank is thrown away and
//   load_go (which requires grp_arm) never fires.
//   The contract bank is loaded one group ahead (shadow, promoted by
//   conv_engine at each group boundary) and the tap words are loaded one
//   group ahead into the alternate bank; a job costs 86 beats against the
//   4,386 beats of one group scan, so nothing stalls meaningfully.
//
// EGRESS SAMPLING (mirror of WINDOWS in scripts/compare_conv1.py)
//   conv_engine emits (out_row, group, col, lane 0..15) in scan order, so the
//   flat sample index is ((row * 3 + grp) * 258 + col) * 16 + lane, channel =
//   grp * 16 + lane, 792,576 samples in total.  Six disjoint 512-sample
//   windows are captured into a 3 KB RAM; the rest is dropped.  The windows
//   cover all 48 channels (all three groups at row 0), the top and bottom pad
//   borders (rows 0 and 63), the left and right borders (columns 0 and 257)
//   and one interior block (row 32, group 1, columns 128..159):
//       0 .. 511         row 0,  grp 0, col 0..31
//       4128 .. 4639     row 0,  grp 1, col 0..31     (channels 16..31)
//       8256 .. 8767     row 0,  grp 2, col 0..31     (channels 32..47)
//       402464 .. 402975 row 32, grp 1, col 128..159  (interior)
//       780192 .. 780703 row 63, grp 0, col 0..31     (bottom + left pad)
//       792064 .. 792575 row 63, grp 2, col 226..257  (right pad)
//
// FRAME FORMAT
//   The 91-byte C-DIAG-UART@1 template of diag_uart_report.v is reused
//   verbatim (no new format, no new field).  diag_uart_report hard-codes the
//   tag names, so the two tags used here keep their existing ASCII text:
//     frame_tag 2 (tag text "DDR3SW") -> CONV1STS status frame, sent 3x
//          A = 0x434F4E31 magic "CON1"   B = done flag (1)
//          C = captured count (3072)     D = 32-bit sum of captured samples
//          E = y-stream beat count seen (expected 792576)
//          F = 0                         G = window count (6)
//          H = 0xA5 status magic
//     frame_tag 3 (tag text "DDR3RS") -> CONV1DAT data frame, 128 of them
//          24 u8 samples per frame, little-endian inside each field
//          (field bit[7:0] is the first sample): A=s0..3 B=s4..7
//          C=s8..11 D=s12..15 E=s16..19 F=s20..23
//          G = frame index low byte, H = frame index high byte
//   The repeated status frame makes the capture robust to one lost line.
//
// All logic runs in the 27 MHz clk domain; reset is asynchronous active low.
// ---------------------------------------------------------------------------

module top_npu_conv1_test #(
    // 115200 8N1 at 27 MHz: round(27e6 / 115200) = 234 (+0.16% baud error).
    parameter integer BAUD_DIV = 234
) (
    input  wire       clk,        // 27 MHz board clock (D18)
    input  wire       rst_n,      // asynchronous board reset (C22)
    output wire [7:0] led,        // status LEDs
    output wire       uart_tx     // 115200 8N1 diagnostic frames (C24)
);

    // -----------------------------------------------------------------------
    // Geometry / capture constants (mirror of scripts/compare_conv1.py)
    // -----------------------------------------------------------------------
    localparam [6:0]  H_ROWS      = 7'd64;      // conv1 output rows
    localparam [8:0]  W_COLS      = 9'd258;     // conv1 output columns
    localparam [19:0] STREAM_END  = 20'd792576; // 64*3*258*16 egress samples

    localparam [19:0] WIN_SPAN    = 20'd512;    // samples per capture window
    localparam [19:0] WIN_BASE_1  = 20'd4128;   // row 0,  grp 1, col 0
    localparam [19:0] WIN_BASE_2  = 20'd8256;   // row 0,  grp 2, col 0
    localparam [19:0] WIN_BASE_3  = 20'd402464; // row 32, grp 1, col 128
    localparam [19:0] WIN_BASE_4  = 20'd780192; // row 63, grp 0, col 0
    localparam [19:0] WIN_BASE_5  = 20'd792064; // row 63, grp 2, col 226

    localparam [11:0] CAP_DEPTH   = 12'd3072;   // 6 windows * 512 samples
    localparam [11:0] CAP_LAST    = 12'd3071;
    localparam [7:0]  FRAME_LAST  = 8'd127;     // last data frame index
    localparam [7:0]  FRAME_OVER  = 8'd128;     // one past the last frame
    localparam [1:0]  STS_REPEAT  = 2'd3;       // status frames before data

    localparam [31:0] STS_MAGIC   = 32'h434F4E31;  // ASCII "CON1"
    localparam [7:0]  STS_TAIL    = 8'hA5;
    localparam [7:0]  WIN_COUNT   = 8'd6;

    // -----------------------------------------------------------------------
    // On-chip tables ($readmemh, work_dir relative: hex_conv1/*.hex)
    // -----------------------------------------------------------------------
    reg [31:0] w_rom  [0:107];   // 27 tap words x 4 sub-words
    reg [31:0] ctr_rom[0:143];   // 48 bias, 48 M, 48 shift
    reg [7:0]  feat_rom[0:16511];

    initial begin
        $readmemh("hex_conv1/conv1_w32.hex",  w_rom);
        $readmemh("hex_conv1/conv1_ctr.hex",  ctr_rom);
        $readmemh("hex_conv1/conv1_feat.hex", feat_rom);
    end

    // Synchronous ROM read ports (one beat of latency, address prefetched).
    reg  [6:0]  w_addr;
    reg  [7:0]  ctr_addr;
    reg  [14:0] feat_addr;
    reg  [31:0] w_dout;
    reg  [31:0] ctr_dout;
    reg  [7:0]  feat_dout;

    always @(posedge clk) begin
        w_dout <= w_rom[w_addr];
    end
    always @(posedge clk) begin
        ctr_dout <= ctr_rom[ctr_addr];
    end
    always @(posedge clk) begin
        feat_dout <= feat_rom[feat_addr];
    end

    // -----------------------------------------------------------------------
    // conv_engine port nets
    // -----------------------------------------------------------------------
    reg                cfg_valid;
    reg          [7:0] cfg_zp_in;
    reg          [7:0] cfg_zp_out;
    reg          [1:0] conv_sel;
    reg                start0;
    wire               done0;
    wire               done1, done2, done3;
    wire [15:0]        x0_ingress_max_row_unused;

    wire               x0_valid;
    wire         [7:0] x0_u8;

    reg                grp_start;
    reg                bias_valid;
    reg  signed [31:0] bias_s32;
    reg                mult_valid;
    reg  signed [31:0] m_s32;
    reg                shft_valid;
    reg          [6:0] shift_w;

    reg                w_valid;
    reg        [127:0] w_data;
    wire               w_ready;

    wire               y_valid;
    wire         [7:0] y_u8;

    wire               adv0;
    wire               adv1, adv2, adv3;

    // -----------------------------------------------------------------------
    // Group / tap bookkeeping
    // -----------------------------------------------------------------------
    // use_grp : output-channel group currently being scanned (0..2).  The tap
    //           bank it reads is bank (use_grp & 1) because the three groups
    //           rotate through two banks (0, 1, 0, 1, ...).
    // job_grp : group whose contract/taps are being prefetched.  At a boundary
    //           conv_engine promotes the shadow contract, so the prefetch
    //           target is (use_grp + 2) % 3 -- one group AFTER the one the
    //           engine is about to scan.
    localparam [1:0] GT_IDLE = 2'd0;   // waiting for a launch
    localparam [1:0] GT_CTR  = 2'd1;   // 49-beat group contract
    localparam [1:0] GT_TAP  = 2'd2;   // 37-beat tap word load

    reg  [1:0] use_grp;
    reg  [1:0] job_grp;
    reg  [3:0] tap_idx;       // 0..8 within the current group
    reg  [1:0] gt_step;       // GT_IDLE / GT_CTR / GT_TAP
    reg        gt_launch;     // 1-beat launch request into GT_CTR
    reg  [5:0] c_step;        // 0..48, beat 0 = grp_start only
    reg  [5:0] t_step;        // 0..36, beat 0 = address prefetch only
    reg        gt_done;       // 1-beat job completion pulse

    // One tap bank PER output group (T25 fix).  The three groups rotate
    // through the scan continuously, so a two-bank ping-pong CANNOT work:
    // group 2 reads bank 0, and the job launched at the end of group 1
    // (which reloads group 0's taps) would overwrite bank 0 while group 2
    // is still scanning it.  The symptom was channels 32..47 producing the
    // group-0 result for the whole frame.
    reg [127:0] tap_bank0 [0:8];
    reg [127:0] tap_bank1 [0:8];
    reg [127:0] tap_bank2 [0:8];
    reg [127:0] tap_ld_acc[0:8];
    reg [127:0] w_tap_word;

    // -----------------------------------------------------------------------
    // Contract ROM address decode (T25 fix)
    // -----------------------------------------------------------------------
    // The contract ROM is BLOCK major: 0..47 = all 48 bias words,
    // 48..95 = all 48 M words, 96..143 = all 48 shift words, and inside a
    // block the 16 words of one output group are consecutive.  conv_engine
    // instead consumes one group as 16 bias -> 16 M -> 16 shift, i.e. a
    // group's 48 logical words are three 16-word slices at three different
    // block bases.  The pre-fix code walked ONE consecutive 48-word window
    // per group (ctr_base = 0 / 48 / 96 on a SIX-bit wire, so 96 also
    // truncated to 32), which loaded bias[16..31] as group 0's M, M[0..15]
    // as group 1's bias and so on.
    //
    // The contract ROM adds one beat of latency on top of the address
    // register, and conv_engine samples one beat after that, so the word
    // reaching conv_engine during beat c_step was ADDRESSED two beats
    // earlier:
    //     dout(c_step = k) = ctr_rom[ctr_addr(c_step = k - 2)]
    // Beat 1 must therefore carry logical word 0 (bias[0]), i.e. the
    // address written on beat k is logical word k + 1, and logical word 0
    // is prefetched on the launch edge.  (The pre-fix code wrote
    // base + c_step, which shifted the whole 48-word sequence by one:
    // bias[0] was loaded twice, bias[15] became M[0] and M[15] became
    // shift[0] -- exactly what the T25 simulator trace shows.)
    wire [5:0] c_logi   = c_step + 6'd1;       // 1..48, 48 is a don't care
    wire [7:0] ctr_off = ((c_logi >= 6'd32) ? 8'd96 :
                          (c_logi >= 6'd16) ? 8'd48 : 8'd0)
                       + {2'd0, job_grp, 4'd0}     // group base * 16
                       + {4'd0, c_logi[3:0]};      // lane inside the block
    wire [6:0] w_base   = (job_grp == 2'd0) ? 7'd0 :
                          (job_grp == 2'd1) ? 7'd36 : 7'd72;
    wire [1:0] use_next = (use_grp == 2'd2) ? 2'd0 : use_grp + 2'd1;
    wire [1:0] job_next = (use_grp == 2'd0) ? 2'd2 :
                          (use_grp == 2'd1) ? 2'd0 : 2'd1;

    // Tap word presented to conv_engine: 9:1 mux over the active bank.
    always @* begin
        if (use_grp == 2'd2)
            w_tap_word = tap_bank2[tap_idx];
        else if (use_grp[0])
            w_tap_word = tap_bank1[tap_idx];
        else
            w_tap_word = tap_bank0[tap_idx];
    end

    // Contract beat decode.  c_step 0 is the grp_start beat only (see the
    // protocol note in the header); beats 1..48 carry the 48 contract words.
    wire       c_bias = (c_step >= 6'd1) && (c_step <= 6'd16);
    wire       c_mult = (c_step >= 6'd17) && (c_step <= 6'd32);
    wire       c_shft = (c_step >= 6'd33) && (c_step <= 6'd48);

    // Tap-load decode: t_step 1..36 -> tap (t_step-1)/4, sub (t_step-1)%4.
    wire [5:0]   t_pair   = t_step - 6'd1;
    wire [3:0]   ld_tap   = t_pair[5:2];
    wire [1:0]   ld_sub   = t_pair[1:0];
    wire [127:0] acc_next = {w_dout, tap_ld_acc[ld_tap][127:32]};

    // -----------------------------------------------------------------------
    // Main sequencer
    // -----------------------------------------------------------------------
    localparam [2:0] S_CFG    = 3'd0;   // latch zp_in / zp_out
    localparam [2:0] S_START  = 3'd1;   // conv layer start pulse
    localparam [2:0] S_BOOT   = 3'd2;   // contract+taps for groups 0 and 1
    localparam [2:0] S_RUN    = 3'd3;   // steady state scan
    localparam [2:0] S_STOP   = 3'd4;   // conv finished, settle before frames
    localparam [2:0] S_REPORT = 3'd5;   // UART frame engine

    reg  [2:0] seq;
    reg  [1:0] boot_job;        // 0 = group 0 job, 1 = group 1 job
    reg  [7:0] settle_cnt;
    reg        done_latched;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            seq          <= S_CFG;
            boot_job     <= 2'd0;
            settle_cnt   <= 8'd0;
            done_latched <= 1'b0;
            cfg_valid    <= 1'b0;
            cfg_zp_in    <= 8'd49;
            cfg_zp_out   <= 8'd0;
            conv_sel     <= 2'd0;
            start0       <= 1'b0;
            gt_step      <= GT_IDLE;
            gt_launch    <= 1'b0;
            gt_done      <= 1'b0;
            c_step       <= 6'd0;
            t_step       <= 6'd0;
            job_grp      <= 2'd0;
            use_grp      <= 2'd0;
            tap_idx      <= 4'd0;
            ctr_addr     <= 8'd0;
            w_addr       <= 7'd0;
        end else begin
            gt_done   <= 1'b0;
            cfg_valid <= 1'b0;
            start0    <= 1'b0;

            // ---- main sequence ----
            case (seq)
                S_CFG: begin
                    cfg_valid <= 1'b1;
                    seq       <= S_START;
                end

                // start0 must come BEFORE the first contract load: conv_engine
                // clears grp_arm (and the ingress counters / row bitmap) on
                // any_start, so a contract loaded beforehand would be thrown
                // away and the engine would wait for grp_arm forever.
                S_START: begin
                    start0    <= 1'b1;
                    use_grp   <= 2'd0;
                    tap_idx   <= 4'd0;
                    boot_job  <= 2'd0;
                    job_grp   <= 2'd0;
                    gt_launch <= 1'b1;
                    seq       <= S_BOOT;
                end

                S_BOOT: begin
                    // One job = contract of group g, then its 27 tap words.
                    // Job 0 loads group 0 into the ACTIVE contract bank and
                    // tap bank 0; job 1 loads group 1 into the SHADOW bank and
                    // tap bank 1 -- exactly the state conv_engine expects when
                    // it starts scanning group 0.
                    if (gt_done) begin
                        if (boot_job == 2'd1) begin
                            seq <= S_RUN;
                        end else begin
                            boot_job  <= 2'd1;
                            job_grp   <= 2'd1;
                            gt_launch <= 1'b1;
                        end
                    end
                end

                S_RUN: begin
                    if (done0) begin
                        done_latched <= 1'b1;
                        settle_cnt   <= 8'd0;
                        seq          <= S_STOP;
                    end else if ((gt_step == GT_IDLE) && !gt_launch) begin
                        if (adv0) begin
                            use_grp   <= use_next;
                            job_grp   <= job_next;
                            gt_launch <= 1'b1;
                            tap_idx   <= 4'd0;
                        end else if (w_valid && w_ready) begin
                            tap_idx <= (tap_idx == 4'd8) ? 4'd0
                                                         : tap_idx + 4'd1;
                        end
                    end
                end

                S_STOP: begin
                    // The last pixel's 16-beat drain completes inside
                    // conv_engine's done0 tail, but a short settle keeps the
                    // capture RAM stable before the frame engine reads it.
                    settle_cnt <= settle_cnt + 8'd1;
                    if (settle_cnt == 8'd255)
                        seq <= S_REPORT;
                end

                default: begin
                    seq <= S_REPORT;
                end
            endcase

            // ---- contract / tap preload job engine ----
            // gt_launch is consumed on the same edge that job_grp becomes
            // visible, so the first CTR beat (c_step 0) already reads the new
            // group's ROM base.  Splitting launch from the state walk is what
            // removes the one-beat group-index skew of the naive version.
            if (gt_step == GT_IDLE) begin
                if (gt_launch) begin
                    gt_launch <= 1'b0;
                    gt_step   <= GT_CTR;
                    c_step    <= 6'd0;
                    // prefetch logical word 0 (bias[0]) of this group
                    ctr_addr  <= {2'd0, job_grp, 4'd0};
                end
            end else if (gt_step == GT_CTR) begin
                if (c_step < 6'd47)
                    ctr_addr <= ctr_off;
                if (c_step == 6'd48) begin
                    c_step  <= 6'd0;
                    t_step  <= 6'd0;
                    gt_step <= GT_TAP;
                    // prefetch tap sub-word 0 (see the TAP note below)
                    w_addr  <= w_base;
                end else begin
                    c_step <= c_step + 6'd1;
                end
            end else begin
                // Tap sub-word prefetch (T25 fix).  Neither the ROM nor the
                // assembler registers the data, so the sub-word written on
                // beat t_step is the one addressed TWO beats earlier:
                //     written(t_step = k) = w_rom[w_addr(t_step = k - 2)]
                // Sub-word 0 must land on t_step = 1, so w_addr(t_step = j)
                // = base + j + 1, and base + 0 is prefetched on the last
                // contract beat.  The pre-fix code wrote base + t_step,
                // which rotated every tap's four 32-bit sub-words by one
                // slot: lane 4..15 took the weights of lane 0..11 and
                // lane 0..3 kept stale data (visible as an acc_snap whose
                // lane k equals the model's lane k - 4).
                if (t_step < 6'd35)
                    w_addr <= w_base + {1'b0, t_step} + 7'd1;
                if (t_step == 6'd36) begin
                    t_step  <= 6'd0;
                    gt_step <= GT_IDLE;
                    gt_done <= 1'b1;
                end else begin
                    t_step <= t_step + 6'd1;
                end
            end

            // ---- tap word assembly (4 sub-words -> one 128-bit tap) ----
            if ((gt_step == GT_TAP) && (t_step != 6'd0)) begin
                tap_ld_acc[ld_tap] <= acc_next;
                if (ld_sub == 2'd3) begin
                    if (job_grp == 2'd2)      tap_bank2[ld_tap] <= acc_next;
                    else if (job_grp[0])      tap_bank1[ld_tap] <= acc_next;
                    else                      tap_bank0[ld_tap] <= acc_next;
                end
            end
        end
    end

    // -----------------------------------------------------------------------
    // Contract / weight / tap-index drive toward conv_engine
    // -----------------------------------------------------------------------
    always @* begin
        grp_start  = (gt_step == GT_CTR) && (c_step == 6'd0);
        bias_valid = (gt_step == GT_CTR) && c_bias;
        mult_valid = (gt_step == GT_CTR) && c_mult;
        shft_valid = (gt_step == GT_CTR) && c_shft;
        bias_s32   = ctr_dout;
        m_s32      = ctr_dout;
        shift_w    = ctr_dout[6:0];
        w_data     = w_tap_word;
        // The tap stream is offered only while no preload job is running.  A
        // zero w_valid parks conv_engine inside PH_SCAN (it waits for w_valid
        // before each tap), which is how the 86-beat preload window after
        // every group boundary is absorbed without extra state.
        w_valid    = (seq == S_RUN) && (gt_step == GT_IDLE) && !gt_launch;
    end

    // -----------------------------------------------------------------------
    // conv_engine instance (default parameters: conv1 = 1 in / 48 out /
    // 64 x 258; conv2..conv4 shapes are unused but kept at their compiled
    // values so this core is bit-identical to the full-NPU instance)
    // -----------------------------------------------------------------------
    conv_engine u_conv (
        .clk         (clk),
        .rst_n       (rst_n),
        .cfg_valid   (cfg_valid),
        .cfg_zp_in   (cfg_zp_in),
        .cfg_zp_out  (cfg_zp_out),
        .conv_sel    (conv_sel),
        .start0      (start0),
        .start1      (1'b0),
        .start2      (1'b0),
        .start3      (1'b0),
        .done0       (done0),
        .done1       (done1),
        .done2       (done2),
        .done3       (done3),
        .x0_valid    (x0_valid),
        .x0_u8       (x0_u8),
        .x0_ingress_max_row (x0_ingress_max_row_unused),
        .x1_valid    (1'b0),
        .x1_u8       (8'd0),
        .x2_valid    (1'b0),
        .x2_u8       (8'd0),
        .x3_valid    (1'b0),
        .x3_u8       (8'd0),
        .grp_start   (grp_start),
        .bias_valid  (bias_valid),
        .bias_s32    (bias_s32),
        .mult_valid  (mult_valid),
        .m_s32       (m_s32),
        .shft_valid  (shft_valid),
        .shift       (shift_w),
        .w_valid     (w_valid),
        .w_data      (w_data),
        .w_ready     (w_ready),
        .y_valid     (y_valid),
        .y_ready     (1'b1),
        .y_u8        (y_u8),
        .adv0        (adv0),
        .adv1        (adv1),
        .adv2        (adv2),
        .adv3        (adv3)
    );

    // -----------------------------------------------------------------------
    // Feature-map ingress replay (3 stages: ROM address -> data -> x0 valid)
    // -----------------------------------------------------------------------
    reg  [6:0] ing_row;
    reg  [8:0] ing_col;
    reg  [6:0] row_done_cnt;   // rows fully scanned (adv0 count / 3)
    reg  [1:0] adv_mod;
    reg        feat_vld1;
    reg        x0_valid_r;
    reg  [7:0] x0_u8_r;

    // Ingress may only write row r+2 once row r has been scanned: the 3-bank
    // line buffer maps row k to bank k%3, so writing row k destroys row k-3,
    // and row k-3 is still a window row (dy = 0) while row k-2 is scanned.
    // Requiring ing_row <= row_done_cnt + 1 keeps every write strictly behind
    // the scan and costs only ~2% of the runtime (258 beats per row against
    // 13,158 beats of row scan).
    wire ing_go = (seq == S_RUN) && !done_latched &&
                  (ing_row < H_ROWS) && (ing_row <= (row_done_cnt + 7'd1));

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            ing_row      <= 7'd0;
            ing_col      <= 9'd0;
            feat_addr    <= 15'd0;
            feat_vld1    <= 1'b0;
            x0_valid_r   <= 1'b0;
            x0_u8_r      <= 8'd0;
            row_done_cnt <= 7'd0;
            adv_mod      <= 2'd0;
        end else begin
            feat_vld1  <= ing_go;
            x0_valid_r <= feat_vld1;
            x0_u8_r    <= feat_dout;

            if (seq == S_START) begin
                ing_row      <= 7'd0;
                ing_col      <= 9'd0;
                feat_addr    <= 15'd0;
                row_done_cnt <= 7'd0;
                adv_mod      <= 2'd0;
            end else if (ing_go) begin
                feat_addr <= feat_addr + 15'd1;
                if (ing_col == (W_COLS - 9'd1)) begin
                    ing_col <= 9'd0;
                    ing_row <= ing_row + 7'd1;
                end else begin
                    ing_col <= ing_col + 9'd1;
                end
            end

            if (adv0) begin
                adv_mod <= (adv_mod == 2'd2) ? 2'd0 : adv_mod + 2'd1;
                if (adv_mod == 2'd2)
                    row_done_cnt <= row_done_cnt + 7'd1;
            end
        end
    end

    assign x0_valid = x0_valid_r;
    assign x0_u8    = x0_u8_r;

    // -----------------------------------------------------------------------
    // Egress sampling: y-stream position counter + six capture windows
    // -----------------------------------------------------------------------
    reg  [19:0] y_cnt;
    reg  [11:0] cap_wp;
    reg  [31:0] cap_sum;
    reg  [7:0]  cap_ram [0:3071];
    reg  [7:0]  cap_dout;
    reg  [11:0] cap_rd_addr;

    wire [19:0] win1_off = y_cnt - WIN_BASE_1;
    wire [19:0] win2_off = y_cnt - WIN_BASE_2;
    wire [19:0] win3_off = y_cnt - WIN_BASE_3;
    wire [19:0] win4_off = y_cnt - WIN_BASE_4;
    wire [19:0] win5_off = y_cnt - WIN_BASE_5;

    wire in_window = (y_cnt < WIN_SPAN) ||
                     (win1_off < WIN_SPAN) || (win2_off < WIN_SPAN) ||
                     (win3_off < WIN_SPAN) || (win4_off < WIN_SPAN) ||
                     (win5_off < WIN_SPAN);

    wire cap_wr = y_valid && in_window && (cap_wp <= CAP_LAST);

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            y_cnt   <= 20'd0;
            cap_wp  <= 12'd0;
            cap_sum <= 32'd0;
        end else if (seq == S_START) begin
            y_cnt   <= 20'd0;
            cap_wp  <= 12'd0;
            cap_sum <= 32'd0;
        end else begin
            if (y_valid && (y_cnt != STREAM_END))
                y_cnt <= y_cnt + 20'd1;
            if (cap_wr) begin
                cap_wp  <= cap_wp + 12'd1;
                cap_sum <= cap_sum + {24'd0, y_u8};
            end
        end
    end

    // Single-port capture RAM: written during the scan, read only after the
    // conv engine has finished, so one port is sufficient.
    always @(posedge clk) begin
        if (cap_wr) cap_ram[cap_wp] <= y_u8;
        cap_dout <= cap_ram[cap_rd_addr];
    end

    // -----------------------------------------------------------------------
    // Frame assembly + frame engine (3 status frames then 128 data frames)
    // -----------------------------------------------------------------------
    localparam [1:0] F_IDLE = 2'd0;
    localparam [1:0] F_WAIT = 2'd1;
    localparam [1:0] F_DONE = 2'd2;

    reg  [7:0]  dsb [0:23];
    reg  [4:0]  ro_i;          // 0..24 readout beat, 25 = idle
    reg  [11:0] ro_base;       // cap_ram base of the block being loaded
    reg         ro_arm;        // arm the next 24-sample block (1 beat later)
    reg  [7:0]  fidx;          // data frame index currently being sent
    reg  [1:0]  sts_cnt;       // status frames still to send (3 -> 0)
    reg  [1:0]  fstate;
    reg         report_fire;
    reg         rep_busy_d;
    reg         report_done;
    reg  [31:0] fa, fb, fc, fd, fe, ff;
    reg  [7:0]  fg, fh;

    wire rep_busy;
    wire busy_fall = rep_busy_d && !rep_busy;
    wire [1:0] frame_tag = (sts_cnt != 2'd0) ? 2'd2 : 2'd3;
    wire [11:0] ro_base_next = ro_base + 12'd24;

    always @* begin
        if (frame_tag == 2'd2) begin
            fa = STS_MAGIC;
            fb = {31'd0, done_latched};
            fc = {20'd0, cap_wp};
            fd = cap_sum;
            fe = {12'd0, y_cnt};
            ff = 32'd0;
            fg = WIN_COUNT;
            fh = STS_TAIL;
        end else begin
            fa = {dsb[3],  dsb[2],  dsb[1],  dsb[0]};
            fb = {dsb[7],  dsb[6],  dsb[5],  dsb[4]};
            fc = {dsb[11], dsb[10], dsb[9],  dsb[8]};
            fd = {dsb[15], dsb[14], dsb[13], dsb[12]};
            fe = {dsb[19], dsb[18], dsb[17], dsb[16]};
            ff = {dsb[23], dsb[22], dsb[21], dsb[20]};
            fg = fidx;
            fh = 8'd0;
        end
    end

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            fstate      <= F_IDLE;
            report_fire <= 1'b0;
            rep_busy_d  <= 1'b0;
            sts_cnt     <= STS_REPEAT;
            fidx        <= 8'd0;
            ro_i        <= 5'd25;
            ro_base     <= 12'd0;
            ro_arm      <= 1'b0;
            report_done <= 1'b0;
            cap_rd_addr <= 12'd0;
        end else begin
            report_fire <= 1'b0;
            rep_busy_d  <= rep_busy;

            // ---- arm the next readout block (one beat after a fire) ----
            if (ro_arm) begin
                ro_arm      <= 1'b0;
                ro_base     <= ro_base_next;
                ro_i        <= 5'd0;
                cap_rd_addr <= ro_base_next;
            end

            // ---- 24-sample readout into dsb (runs between two frames) ----
            // The capture RAM has one beat of synchronous read latency and
            // cap_dout is clocked on the same edge as cap_rd_addr, so the
            // address has to run ONE SLOT AHEAD of the dsb slot being
            // filled:
            //     cap_rd_addr(ro_i = k) = ro_base + k + 1
            //     dsb[ro_i - 1] <= cap_dout       (cap_ram[ro_base + ro_i - 1])
            // and ro_base itself is prefetched on the arming edge (see the
            // fstate block below).  The pre-T25 code loaded the address and
            // the dsb slot on the same edge, which left every 24-sample
            // frame shifted by one sample: dsb[0] took cap_ram[base - 1]
            // and dsb[k] took cap_ram[base + k - 1] (T25 bug D-06).
            if (ro_i < 5'd25) begin
                if (ro_i < 5'd23)
                    cap_rd_addr <= ro_base + {7'd0, ro_i} + 12'd1;
                if (ro_i != 5'd0)
                    dsb[ro_i - 5'd1] <= cap_dout;
                ro_i <= ro_i + 5'd1;
            end

            // ---- frame sequencing: fire only while the reporter is idle ----
            case (fstate)
                F_IDLE: begin
                    if ((seq == S_REPORT) && !rep_busy) begin
                        report_fire <= 1'b1;
                        fidx        <= 8'd0;
                        ro_base     <= 12'd0;
                        ro_i        <= 5'd0;
                        // prefetch the first readout address (see the
                        // readout block above)
                        cap_rd_addr <= 12'd0;
                        fstate      <= F_WAIT;
                    end
                end

                F_WAIT: begin
                    if (busy_fall) begin
                        if (sts_cnt != 2'd0) begin
                            // still in the repeated status-frame preamble
                            sts_cnt     <= sts_cnt - 2'd1;
                            report_fire <= 1'b1;
                            // the last status frame also arms the first
                            // DATA block, so data frame 0 already carries
                            // cap[0..23] and frame 1 carries cap[24..47]
                            if (sts_cnt == 2'd1)
                                ro_arm <= 1'b1;
                        end else if (fidx == FRAME_OVER) begin
                            report_done <= 1'b1;
                            fstate      <= F_DONE;
                        end else begin
                            report_fire <= 1'b1;
                            fidx        <= fidx + 8'd1;
                            // Arm the NEXT block one beat AFTER this frame
                            // fires (T25 fix D-07).  Arming on the same edge
                            // as the fire left the readout permanently one
                            // frame behind: measured in simulation, the
                            // readout for frame f completed 24 cycles after
                            // frame f had already been latched, so every
                            // data frame carried block f-1 and the last
                            // frame carried a duplicate of block 126.
                            if (fidx != FRAME_LAST)
                                ro_arm <= 1'b1;
                        end
                    end
                end

                default: begin
                    fstate <= F_DONE;
                end
            endcase
        end
    end

    // -----------------------------------------------------------------------
    // Diagnostic frame producer + UART transmitter
    // -----------------------------------------------------------------------
    wire [7:0] tx_byte_data;
    wire       tx_byte_valid;
    wire       tx_byte_ready;

    diag_uart_report #(
        .BAUD_DIV    (BAUD_DIV)
    ) u_report (
        .clk           (clk),
        .rst_n         (rst_n),
        .fire          (report_fire),
        .frame_tag     (frame_tag),
        .f_a           (fa),
        .f_b           (fb),
        .f_c           (fc),
        .f_d           (fd),
        .f_e           (fe),
        .f_f           (ff),
        .f_g           (fg),
        .f_h           (fh),
        .busy          (rep_busy),
        .tx_byte_data  (tx_byte_data),
        .tx_byte_valid (tx_byte_valid),
        .tx_byte_ready (tx_byte_ready)
    );

    uart_tx #(
        .BAUD_DIV    (BAUD_DIV)
    ) u_uart_tx (
        .clk        (clk),
        .rst_n      (rst_n),
        .byte_wdata (tx_byte_data),
        .byte_wvalid(tx_byte_valid),
        .byte_wready(tx_byte_ready),
        .uart_txd   (uart_tx)
    );

    // -----------------------------------------------------------------------
    // Status LEDs
    //   led[0] 27 MHz heartbeat (~3.2 Hz)   led[1] conv1 done latched
    //   led[2] all frames sent              led[3] capture RAM full
    //   led[4] scan running                 led[5] UART frame in flight
    // -----------------------------------------------------------------------
    reg [22:0] hb_cnt;
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) hb_cnt <= 23'd0;
        else        hb_cnt <= hb_cnt + 23'd1;
    end

    assign led[0] = hb_cnt[22];
    assign led[1] = done_latched;
    assign led[2] = report_done;
    assign led[3] = (cap_wp == CAP_DEPTH);
    assign led[4] = (seq == S_RUN);
    assign led[5] = rep_busy;
    assign led[6] = 1'b0;
    assign led[7] = 1'b0;

endmodule
